// Requer scripts/benchmark.py --serve e Chromium com CDP. Só usa dados simulados.
import assert from 'node:assert/strict';
const origin=process.env.PANEL_ORIGIN||'http://127.0.0.1:8083/';
const tabs=await (await fetch(`http://127.0.0.1:${process.env.CDP_PORT||9222}/json/list`)).json();
const socket=new WebSocket(tabs.find(tab=>tab.type==='page').webSocketDebuggerUrl);
await new Promise((resolve,reject)=>{socket.onopen=resolve;socket.onerror=reject;});
let sequence=0;const pending=new Map(),requests=[],errors=[];
socket.onmessage=event=>{
  const message=JSON.parse(event.data);
  if(message.id){const item=pending.get(message.id);pending.delete(message.id);message.error?item.reject(new Error(message.error.message)):item.resolve(message.result);}
  if(message.method==='Network.requestWillBeSent')requests.push(message.params.request.url);
  if(message.method==='Runtime.exceptionThrown')errors.push(message.params.exceptionDetails.text);
};
const call=(method,params={})=>new Promise((resolve,reject)=>{const id=++sequence;pending.set(id,{resolve,reject});socket.send(JSON.stringify({id,method,params}));});
const evaluate=async expression=>{const result=await call('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true});if(result.exceptionDetails)throw new Error(JSON.stringify(result.exceptionDetails));return result.result.value;};
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const wait=async expression=>{for(let i=0;i<200;i++){if(await evaluate(expression))return;await delay(50);}throw new Error('Tempo excedido: '+expression);};
const count=resource=>requests.filter(url=>url.includes('/api/read?')&&new URL(url).searchParams.get('resource')===resource).length;
const navigate=async page=>{const previous=await evaluate('generation');await evaluate(`location.hash=${JSON.stringify(page)}`);await wait(`generation>${previous}&&!document.querySelector('#content').hasAttribute('aria-busy')`);};
try{
  await call('Runtime.enable');await call('Page.enable');await call('Network.enable');
  await call('Emulation.setDeviceMetricsOverride',{width:1440,height:1000,deviceScaleFactor:1,mobile:false});
  await call('Page.navigate',{url:origin});
  await wait("typeof api==='function'&&!!document.querySelector('#login-form')");
  await evaluate("document.querySelector('[name=username]').value='fixture';document.querySelector('[name=password]').value='fixture-only';document.querySelector('#login-form').requestSubmit()");
  await wait("!document.querySelector('#shell').hidden&&!document.querySelector('#content').hasAttribute('aria-busy')");
  assert.equal(await evaluate('session.low_resource'),true);
  const initialInventories=count('instance-list'),initialServers=count('server');
  assert.equal(initialInventories,1);assert.equal(initialServers,1);
  assert.equal(count('pools'),0);assert.equal(count('pool-resources'),0);
  for(const page of ['settings','profiles','networks','server','instances'])await navigate(page);
  assert.equal(count('instance-list'),initialInventories);
  assert.equal(count('server'),initialServers);
  assert.equal(await evaluate("document.querySelectorAll('#content tbody tr').length"),25);
  assert.equal(await evaluate("document.querySelectorAll('#tree .leaf').length"),25);
  const firstRow=await evaluate("document.querySelector('#content tbody tr').textContent");
  await evaluate("[...document.querySelectorAll('.pagination button')].find(button=>button.textContent==='Próxima').click()");
  assert.notEqual(await evaluate("document.querySelector('#content tbody tr').textContent"),firstRow);
  await evaluate("const input=document.querySelector('[aria-label=\"Buscar containers\"]');input.value='lab-db';input.dispatchEvent(new Event('input'))");
  await wait("document.querySelectorAll('#content tbody tr').length===1");
  assert.equal(await evaluate("document.querySelector('#content tbody tr').textContent.includes('lab-db')"),true);
  let previous=await evaluate('generation');
  await evaluate("document.querySelector('#refresh').click()");
  await wait(`generation>${previous}&&!document.querySelector('#content').hasAttribute('aria-busy')`);
  assert.equal(count('instance-list'),initialInventories+1);
  assert.equal(count('server'),initialServers+1);
  await navigate('profiles');
  assert.equal(await evaluate("document.querySelector('#content details pre')===null"),true);
  await evaluate("document.querySelector('#content details').open=true");
  await wait("!!document.querySelector('#content details pre')");
  const initialStates=count('state');
  await navigate('instance/lab-web/devices');await navigate('instance/lab-web/options');
  assert.equal(count('state'),initialStates);
  await navigate('instance/lab-web/summary');assert.equal(count('state'),initialStates+1);
  await evaluate("api('/api/action',{host:'demo',project:'laboratorio',action:'start',target:'lab-db',confirmation:'demo/laboratorio/lab-db'}).then(result=>waitOperation(result.operation,{host:'demo',project:'laboratorio'},session))");
  await navigate('instances');
  assert.equal(count('instance-list'),initialInventories+2);
  assert.equal(await evaluate("read('instance-list').then(result=>result.data.find(item=>item.name==='lab-db').status)"),'Running');
  previous=await evaluate('generation');
  await evaluate("document.querySelector('#project').value='redes';document.querySelector('#project').dispatchEvent(new Event('change'))");
  await wait(`generation>${previous}&&!document.querySelector('#content').hasAttribute('aria-busy')`);
  assert.equal(await evaluate("document.querySelectorAll('#content tbody tr').length"),2);
  const idleRequests=requests.filter(url=>url.includes('/api/')).length;
  await delay(2300);
  assert.equal(requests.filter(url=>url.includes('/api/')).length,idleRequests);
  await evaluate("const run={owner:session,scope:{host,project},operation:'fixture',status_code:100};Promise.all([pollCreation(run),pollImageDownload(run)])");
  assert.equal(requests.filter(url=>url.includes('/api/')).length,idleRequests);
  assert.equal(await evaluate("getComputedStyle(document.querySelector('#shell header')).backdropFilter"),'none');
  assert.equal(await evaluate("const spinner=el('span',{class:'spinner'});document.body.append(spinner);const animation=getComputedStyle(spinner).animationName;spinner.remove();animation"),'none');
  await evaluate("for(let i=0;i<200;i++)trackTask('fixture-'+i,{status_code:200})");
  assert.equal(await evaluate('tasks.size'),100);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({fixture:true,inventoryQueriesAcrossFivePages:0,visibleTableRows:25,treeLimit:25,pagination:true,search:true,manualRefresh:true,mutationInvalidation:true,projectIsolation:true,idleApiRequests:0,offPagePollingRequests:0,lazyDetails:true,jsErrors:0}));
}finally{socket.close();}
